// Programmatic local env generation for `engager init/setup`. The hosted
// .env.example stays the repo/hosted reference; a LOCAL install needs eight
// keys, half of them computed at init time — so we generate, not template.
// Merge-idempotent: existing keys are never touched (in particular
// ENGAGER_MASTER_KEY and ENGAGER_ORG_ID are never regenerated).
import { parseEnv } from "node:util";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

/** KEY=VALUE pairs currently in the env file (last assignment wins). */
export function readEnvFile(envFile) {
  const map = new Map();
  if (!existsSync(envFile)) return map;
  // Dev validates and loads exactly this grammar before any provisioning.
  if (process.env.ENGAGER_DEV_APP === "1") return new Map(Object.entries(parseEnv(readFileSync(envFile, "utf8"))));
  for (const line of readFileSync(envFile, "utf8").split("\n")) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) map.set(match[1], match[2]);
  }
  return map;
}

/** Update-or-append one key, preserving the rest of the file byte-for-byte. */
export function setEnvKey(envFile, key, value) {
  const line = `${key}=${value}`;
  if (!existsSync(envFile)) {
    mkdirSync(path.dirname(envFile), { recursive: true });
    writeFileSync(envFile, `${line}\n`, { mode: 0o600 });
    return;
  }
  const content = readFileSync(envFile, "utf8");
  const pattern = new RegExp(`^${key}=.*$`, "m");
  const next = pattern.test(content)
    ? content.replace(pattern, line)
    : `${content}${content.endsWith("\n") || content === "" ? "" : "\n"}${line}\n`;
  writeFileSync(envFile, next);
}

/**
 * Ensure the local env file exists with every required key, generating the
 * computable ones and appending only what's missing. Returns the merged map
 * plus which keys were added this run. ENGAGER_ORG_ID is deliberately NOT
 * set here — the org bootstrap step writes it via setEnvKey afterwards.
 *
 * NO PROVIDER API KEYS. Every model call — background jobs included — runs
 * through the owner's own coding-agent CLI on their existing subscription, so
 * there is nothing to paste. Embeddings are optional and already degrade to
 * recency ranking when absent. `assumeYes` is retained for signature
 * compatibility with the prerequisite prompts; nothing here asks anything.
 *
 * `postgres` is the server the prerequisite step actually found — the two URLs
 * are written to point AT it. Hardcoding :5432 here wrote an env file that
 * named a server this machine may not run, and the mistake only surfaced
 * several hundred statements into the migration.
 */
export async function ensureLocalEnv(
  envFile,
  { assumeYes = false, postgres = DEFAULT_POSTGRES } = {},
) {
  void assumeYes;
  const existing = readEnvFile(envFile);
  const osUser = os.userInfo().username;
  const server = `${postgres.host ?? DEFAULT_POSTGRES.host}:${postgres.port ?? DEFAULT_POSTGRES.port}`;
  const required = new Map([
    // Explicit, not inferred: the provider-budget guard REFUSES to bypass
    // enforcement unless this is set literally, so an unset value 503s every
    // model call even though the environment would otherwise resolve to local.
    ["ENGAGER_DEPLOYMENT_ENV", "local"],
    ["DATABASE_URL", `postgresql://engager_app@${server}/engager`],
    ["ENGAGER_MIGRATE_DATABASE_URL", `postgresql://${osUser}@${server}/engager`],
    ["ENGAGER_MASTER_KEY", () => randomBytes(32).toString("base64")],
    ["ENGAGER_DRIVER", "browser-use"],
    ["ENGAGER_PAYWALL_ENABLED", "false"],
    // Which agent CLI serves inference; "auto" picks the first installed one.
    ["ENGAGER_AGENT_CLI", "auto"],
  ]);

  const added = [];
  const lines = [];
  for (const [key, value] of required) {
    if (existing.has(key) && existing.get(key) !== "") continue;
    const resolved = typeof value === "function" ? await value() : value;
    // A skipped prompt on an already-present-but-empty key: leave it alone.
    if (existing.has(key) && resolved === "") continue;
    lines.push(`${key}=${resolved}`);
    added.push(key);
  }

  if (lines.length > 0) {
    mkdirSync(path.dirname(envFile), { recursive: true });
    const banner = existsSync(envFile)
      ? `\n# --- added by engager init (${new Date().toISOString().slice(0, 10)}) ---\n`
      : `# Engager local configuration — generated by engager init.\n# Safe to edit; re-running init only appends missing keys.\n`;
    const current = existsSync(envFile) ? readFileSync(envFile, "utf8") : "";
    const glue = current === "" || current.endsWith("\n") ? "" : "\n";
    writeFileSync(envFile, `${current}${glue}${banner}${lines.join("\n")}\n`, { mode: 0o600 });
  }

  return { env: readEnvFile(envFile), added };
}

/** Where a machine with no env file yet is assumed to keep Postgres — the
 *  starting point of the prerequisite step's search, never its conclusion. */
export const DEFAULT_POSTGRES = { host: "localhost", port: 5432 };

/**
 * The libpq parts of a connection URL: `{ host, port, user, database }`.
 *
 * `createdb` and `psql` take these as flags and otherwise connect to whatever
 * cluster the ambient PGHOST/PGPORT (or the default socket) resolve to — which
 * is how `createdb engager` reported success against one server while the
 * migration connected to another and answered `database "engager" does not
 * exist`. Anything the URL omits comes back undefined so the caller can leave
 * the flag off rather than invent a value.
 */
export function postgresConnection(url) {
  if (!url) return null;
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    return null;
  }
  const database = decodeURIComponent(parsed.pathname.replace(/^\//, ""));
  return {
    host: parsed.hostname || undefined,
    port: parsed.port ? Number(parsed.port) : undefined,
    user: parsed.username ? decodeURIComponent(parsed.username) : undefined,
    database: database || undefined,
  };
}

/** Database name from DATABASE_URL (for createdb), defaulting to "engager". */
export function databaseNameFromEnv(env) {
  const url = env.get("DATABASE_URL");
  if (!url) return "engager";
  try {
    const parsed = new URL(url);
    return decodeURIComponent(parsed.pathname.replace(/^\//, "")) || "engager";
  } catch {
    return "engager";
  }
}
