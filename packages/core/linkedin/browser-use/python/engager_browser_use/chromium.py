def screen_size() -> tuple[int, int]:
	"""The main display's size in points, which a headed window is sized to.

	CoreGraphics through ctypes rather than AppKit, so no Objective-C bridge is
	installed for a number the hidden window never shows."""
	if sys.platform != "darwin":
		return FALLBACK_SCREEN
	try:

		class CGRect(ctypes.Structure):
			_fields_ = [("x", ctypes.c_double), ("y", ctypes.c_double), ("width", ctypes.c_double), ("height", ctypes.c_double)]

		graphics = ctypes.CDLL("/System/Library/Frameworks/CoreGraphics.framework/CoreGraphics")
		graphics.CGMainDisplayID.restype = ctypes.c_uint32
		graphics.CGDisplayBounds.restype = CGRect
		graphics.CGDisplayBounds.argtypes = [ctypes.c_uint32]
		bounds = graphics.CGDisplayBounds(graphics.CGMainDisplayID())
		width, height = int(bounds.width), int(bounds.height)
	except (OSError, AttributeError):
		return FALLBACK_SCREEN
	return (width, height) if width > 0 and height > 0 else FALLBACK_SCREEN


def launch_args(
	user_data_dir: Path,
	extra: Sequence[str] = (),
	*,
	headless: bool = False,
	window_position: tuple[int, int] | None = None,
	screen: tuple[int, int] | None = None,
) -> list[str]:
	"""Chromium's command line for one launch, without the debugging port.

	A flag named twice keeps its first place and its last value, as the
	library's own merge did. A headed window is sized to the display and, where
	a position is named, placed there; a headless one has neither."""
	flags = [*DEFAULT_ARGS, *extra, f"--user-data-dir={user_data_dir}", f"--profile-directory={PROFILE_DIRECTORY}"]
	if headless:
		flags.append("--headless=new")
	else:
		width, height = screen or screen_size()
		flags.append(f"--window-size={width},{height}")
		if window_position is not None:
			flags.append(f"--window-position={window_position[0]},{window_position[1]}")
	merged: dict[str, str] = {}
	for flag in flags:
		name, _, value = flag.partition("=")
		merged[name] = value.strip()
	return [f"{name}={value}" if value else name for name, value in merged.items()] + [DISABLE_FEATURES]


def url_allowed(url: str) -> bool:
	"""Whether a tab may be on this address: LinkedIn, or a page that is not a
	site (a blank or new tab, a data or blob document). A tab not yet loaded
	has no address, and says nothing."""
	if not url or url in NEW_TAB_URLS:
		return True
	parsed = urlparse(url)
	if parsed.scheme in {"data", "blob"}:
		return True
	host = parsed.hostname
	return parsed.scheme in {"http", "https"} and host is not None and (host == "linkedin.com" or host.endswith(".linkedin.com"))


def sign_in_page(url: str) -> bool:
	"""Whether this address is a sign-in provider's own page (`SIGN_IN_HOSTS`)."""
	parsed = urlparse(url)
	return parsed.scheme == "https" and parsed.hostname is not None and SIGN_IN_HOSTS.fullmatch(parsed.hostname) is not None


class _Client(CDPClient):
	"""A CDP client whose requests give up: a browser that stops answering is an
	error, not a wait with no end."""

	async def send_raw(self, method: str, params: Any | None = None, session_id: str | None = None) -> dict[str, Any]:
		try:
			return await asyncio.wait_for(super().send_raw(method, params, session_id), timeout=CDP_REQUEST_TIMEOUT_S)
		except TimeoutError as exc:
			raise TimeoutError(f"CDP method {method!r} did not respond within {CDP_REQUEST_TIMEOUT_S:.0f}s") from exc


@dataclass(frozen=True)
class CdpSession:
	"""One tab's session on the browser's CDP client: what a network listener
	or a cookie call is made with."""

	cdp_client: Any
	session_id: str


class Page:
	"""One tab."""

	def __init__(self, browser: Chromium, target_id: str) -> None:
		self._browser = browser
		self.target_id = target_id

	async def evaluate(self, page_function: str, *args: Any) -> str:
		"""Run an arrow function in the tab, awaiting a promise it returns.

		The result is a string: a string as it is, nothing as "", an object or
		array as JSON, and anything else (a boolean, a number) as Python
		spells it -- the sidecar's page scripts return JSON strings, or compare
		against that spelling."""
		function = page_function.strip()
		if not (function.startswith("(") and "=>" in function):
			raise ValueError(f"JavaScript code must start with (...args) => format. Got: {function[:50]}...")
		call = ", ".join(json.dumps(arg) for arg in args)
		session = await self._browser.session_for(self.target_id)
		result = await session.cdp_client.send.Runtime.evaluate(
			params={"expression": f"({function})({call})", "returnByValue": True, "awaitPromise": True},
			session_id=session.session_id,
		)
		if "exceptionDetails" in result:
			raise RuntimeError(f"JavaScript evaluation failed: {result['exceptionDetails']}")
		value = result.get("result", {}).get("value")
		if value is None:
			return ""
		if isinstance(value, str):
			return value
		return json.dumps(value) if isinstance(value, (dict, list)) else str(value)

	async def goto(self, url: str) -> None:
		session = await self._browser.session_for(self.target_id)
		await session.cdp_client.send.Page.navigate(params={"url": url}, session_id=session.session_id)

	async def get_target_info(self) -> dict[str, Any]:
		result = await self._browser.cdp_client.send.Target.getTargetInfo(params={"targetId": self.target_id})
		return result["targetInfo"]

	async def get_url(self) -> str:
		return str((await self.get_target_info()).get("url", ""))

	async def press(self, key: str) -> None:
		"""Press and release one key on the tab's focused element."""
		code, virtual_code = KEY_CODES[key]
		session = await self._browser.session_for(self.target_id)
		for kind in ("keyDown", "keyUp"):
			await session.cdp_client.send.Input.dispatchKeyEvent(
				params={"type": kind, "key": key, "code": code, "windowsVirtualKeyCode": virtual_code},
				session_id=session.session_id,
			)


class Chromium:
	"""A Chromium over one CDP connection: the one this sidecar launched, whose
	process it owns, or one it attached to, which it only ever lets go of."""

	def __init__(self, client: Any, process: asyncio.subprocess.Process | None = None, *, guard: bool = False) -> None:
		self._client = client
		self._process = process
		self._sessions: dict[str, str] = {}
		self._session_locks: dict[str, asyncio.Lock] = {}
		self._guard_locks: dict[str, asyncio.Lock] = {}
		self._background: set[asyncio.Task[Any]] = set()
		# Tabs are held to LinkedIn only in a browser this sidecar launched; a
		# browser it attached to is the owner's, and its other tabs are theirs.
		self._guard = guard
		# Until when a tab may also be on a sign-in provider's page.
		self._sign_in_until = 0.0
		client.register.Page.javascriptDialogOpening(self._on_dialog)
		client.register.Target.detachedFromTarget(self._on_detached)
		if guard:
			client.register.Target.targetCreated(self._on_target_created)
			client.register.Target.targetInfoChanged(self._on_target_changed)

	@property
	def cdp_client(self) -> Any:
		return self._client

	@property
	def pid(self) -> int | None:
		"""The launched browser's process id; None for one attached to."""
		return self._process.pid if self._process is not None else None

	@classmethod
	async def launch(cls, executable: Path, args: Sequence[str]) -> Chromium:
		"""Start `executable` with `args` and a debugging port of its own, and
		connect once that port answers."""
		with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
			probe.bind(("127.0.0.1", 0))
			port = probe.getsockname()[1]
		process = await asyncio.create_subprocess_exec(
			str(executable),
			*args,
			f"--remote-debugging-port={port}",
			stdin=asyncio.subprocess.DEVNULL,
			stdout=asyncio.subprocess.DEVNULL,
			stderr=asyncio.subprocess.DEVNULL,
		)
		try:
			endpoint = await cls._await_endpoint(f"http://127.0.0.1:{port}", process)
			browser = cls(await cls._connect(endpoint), process, guard=True)
		except BaseException:
			await _stop_process(process)
			raise
		try:
			await browser._start()
		except BaseException:
			await browser.kill()
			raise
		return browser

	@classmethod
	async def attach(cls, cdp_url: str) -> Chromium:
		"""Connect to a browser already running, by its `ws://` address or the
		`http://` one that names it."""
		endpoint = cdp_url if cdp_url.startswith("ws") else await cls._debugger_url(cdp_url)
		browser = cls(await cls._connect(endpoint))
		await browser._start()
		return browser

	@staticmethod
	async def _debugger_url(http_url: str) -> str:
		parsed = urlparse(http_url)
		path = parsed.path.rstrip("/")
		if not path.endswith("/json/version"):
			path += "/json/version"
		url = urlunparse((parsed.scheme, parsed.netloc, path, parsed.params, parsed.query, parsed.fragment))
		# A proxy in the environment must not stand between us and a local port.
		local = parsed.hostname in {"localhost", "127.0.0.1", "::1"}
		async with httpx.AsyncClient(timeout=httpx.Timeout(CONNECT_TIMEOUT_S), trust_env=not local) as http:
			return str((await http.get(url)).json()["webSocketDebuggerUrl"])

	@classmethod
	async def _await_endpoint(cls, http_url: str, process: asyncio.subprocess.Process) -> str:
		"""The launched browser's WebSocket address, once its port answers. A
		browser that exits first -- one handed to another instance holding the
		profile -- is an error now, not a wait for a port that never opens."""
		deadline = asyncio.get_running_loop().time() + LAUNCH_TIMEOUT_S
		while asyncio.get_running_loop().time() < deadline:
			if process.returncode is not None:
				raise RuntimeError(f"the browser exited with code {process.returncode} before it opened its debugging port")
			try:
				return await cls._debugger_url(http_url)
			except (httpx.HTTPError, KeyError, ValueError):
				await asyncio.sleep(LAUNCH_POLL_S)
		raise TimeoutError(f"the browser did not open its debugging port within {LAUNCH_TIMEOUT_S:.0f}s")

	@staticmethod
	async def _connect(endpoint: str) -> Any:
		client = _Client(endpoint, max_ws_frame_size=MAX_WS_FRAME_BYTES)
		try:
			await asyncio.wait_for(client.start(), timeout=CONNECT_TIMEOUT_S)
		except BaseException:
			await _stop_client(client)
			raise
		return client

	async def _start(self) -> None:
		"""Watch the browser's tabs where they are held to LinkedIn, and make
		sure there is a tab to work in."""
		try:
			if self._guard:
				await self._client.send.Target.setDiscoverTargets(params={"discover": True})
			await self.page_for_work()
		except BaseException:
			await self.detach()
			raise

	async def page_for_work(self) -> Page:
		"""The tab to work in: the first one open, with a new-tab page turned
		into `about:blank`, or a new blank tab where none is open."""
		pages = await self._page_targets()
		if not pages:
			return await self.new_page()
		first = pages[0]
		if first["url"] in NEW_TAB_URLS and first["url"] != "about:blank":
			session = await self.session_for(first["targetId"])
			await session.cdp_client.send.Page.navigate(params={"url": "about:blank"}, session_id=session.session_id)
		return Page(self, first["targetId"])

	async def _page_targets(self) -> list[dict[str, Any]]:
		result = await self._client.send.Target.getTargets()
		return [info for info in result["targetInfos"] if info.get("type") == "page"]

	async def get_pages(self) -> list[Page]:
		"""Every tab the browser has, in every browser context it holds."""
		return [Page(self, info["targetId"]) for info in await self._page_targets()]

	async def new_page(self) -> Page:
		result = await self._client.send.Target.createTarget(params={"url": "about:blank"})
		return Page(self, result["targetId"])

	async def close_page(self, page: Page) -> None:
		await self._client.send.Target.closeTarget(params={"targetId": page.target_id})
		self._sessions.pop(page.target_id, None)

	async def session_for(self, target_id: str) -> CdpSession:
		"""The one session this connection keeps on a tab, attached on first use.

		One session per tab, so the network events a listener enabled on it,
		the media block set on it and the page functions run in it are all the
		same session. The Page domain is enabled on it because that is what
		reports a dialog, and a dialog nobody answers holds the tab."""
		async with self._session_locks.setdefault(target_id, asyncio.Lock()):
			session_id = self._sessions.get(target_id)
			if session_id is None:
				attached = await self._client.send.Target.attachToTarget(params={"targetId": target_id, "flatten": True})
				session_id = attached["sessionId"]
				await self._client.send.Page.enable(session_id=session_id)
				self._sessions[target_id] = session_id
		return CdpSession(self._client, session_id)

	def _spawn(self, work: Awaitable[Any]) -> None:
		"""Run `work` beside the event handler that asked: a handler runs inside
		the connection's own read loop, so awaiting a reply there would wait on
		the loop it blocks."""
		task = asyncio.ensure_future(work)
		self._background.add(task)
		task.add_done_callback(self._finished)

	def _finished(self, task: asyncio.Task[Any]) -> None:
		self._background.discard(task)
		if not task.cancelled():
			task.exception()  # a refused call on a tab that is gone is not news

	def _on_dialog(self, event: Any, session_id: str | None) -> None:
		if session_id is None:
			return
		accept = event.get("type") in ACCEPTED_DIALOGS
		self._spawn(
			asyncio.wait_for(
				self._client.send.Page.handleJavaScriptDialog(params={"accept": accept}, session_id=session_id),
				timeout=DIALOG_TIMEOUT_S,
			)
		)

	def _on_detached(self, event: Any, _session_id: str | None) -> None:
		gone = event.get("sessionId")
		for target_id, session_id in list(self._sessions.items()):
			if session_id == gone:
				del self._sessions[target_id]

	def _on_target_created(self, event: Any, _session_id: str | None) -> None:
		info = event.get("targetInfo") or {}
		if info.get("type") == "page":
			self._spawn(self._watch_page(str(info["targetId"])))

	def owner_signing_in(self, underway: bool) -> None:
		"""The owner is at the window signing in to LinkedIn, or no longer is.
		While they are, LinkedIn's sign-in page may hand a tab to Google or
		Apple, and the guard lets that tab be. Each look of the sign-in step
		says so again, so a step nobody finished ends by itself
		(`SIGN_IN_LEASE_S`); unattended work never says so, and stays held to
		LinkedIn."""
		self._sign_in_until = time.monotonic() + SIGN_IN_LEASE_S if underway else 0.0

	def signing_in(self) -> bool:
		"""Whether the sign-in step looked recently enough to count as underway."""
		return time.monotonic() < self._sign_in_until

	def signing_in_on(self, url: str | None) -> bool:
		"""Whether the owner's sign-in is underway on this address: a sign-in
		provider's page, while they are signing in."""
		return url is not None and self.signing_in() and sign_in_page(url)

	def _tab_allowed(self, url: str) -> bool:
		return url_allowed(url) or self.signing_in_on(url)

	def _on_target_changed(self, event: Any, _session_id: str | None) -> None:
		info = event.get("targetInfo") or {}
		if info.get("type") == "page" and not self._tab_allowed(str(info.get("url") or "")):
			self._spawn(self._send_back(str(info["targetId"])))

	async def _watch_page(self, target_id: str) -> None:
		await self.session_for(target_id)
		await self._send_back(target_id)

	async def _send_back(self, target_id: str) -> None:
		async with self._guard_locks.setdefault(target_id, asyncio.Lock()):
			session = await self.session_for(target_id)
			info = await self._client.send.Target.getTargetInfo(params={"targetId": target_id})
			if not self._tab_allowed(str(info["targetInfo"].get("url") or "")):
				await session.cdp_client.send.Page.navigate(params={"url": "about:blank"}, session_id=session.session_id)

	async def detach(self) -> None:
		"""Let go of the connection. The browser, if there is one, runs on."""
		for task in list(self._background):
			task.cancel()
		self._sessions.clear()
		await _stop_client(self._client)

	async def kill(self) -> None:
		"""Stop the browser this sidecar launched: terminate it, and kill it if it
		does not go. A browser attached to is left as it is."""
		await self.detach()
		if self._process is not None:
			await _stop_process(self._process)


async def _stop_client(client: Any) -> None:
	try:
		await asyncio.wait_for(client.stop(), timeout=TERMINATE_TIMEOUT_S)
	except Exception:  # noqa: BLE001 -- a connection that is already gone is stopped
		pass


async def _stop_process(process: asyncio.subprocess.Process) -> None:
	if process.returncode is not None:
		return
	try:
		process.terminate()
		await asyncio.wait_for(process.wait(), timeout=TERMINATE_TIMEOUT_S)
	except TimeoutError:
		process.kill()
		await process.wait()
	except ProcessLookupError:
		pass
