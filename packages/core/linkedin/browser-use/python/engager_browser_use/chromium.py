# One CDP request gets this long before the browser is called unresponsive.
CDP_REQUEST_TIMEOUT_S = 60.0
# The WebSocket handshake with a browser that has already answered on HTTP.
CONNECT_TIMEOUT_S = 15.0
# How long a launched Chromium gets to open its debugging port.
LAUNCH_TIMEOUT_S = 30.0
LAUNCH_POLL_S = 0.1
# How long a terminated Chromium gets before it is killed.
TERMINATE_TIMEOUT_S = 5.0
# A page can be very large; the WebSocket frame limit has to hold its DOM.
MAX_WS_FRAME_BYTES = 200 * 1024 * 1024
# Page dialogs are answered on a short leash: the page is waiting.
DIALOG_TIMEOUT_S = 0.5
# The display a headed window is sized to where none can be read.
FALLBACK_SCREEN = (1920, 1080)

# How long past the sign-in step's last look a tab may stay on a sign-in
# provider's page: a second factor on another device takes minutes.
SIGN_IN_LEASE_S = 300.0
# Where LinkedIn's sign-in page hands the owner to sign in with another
# account: Google, on its per-country hosts and the YouTube hop its sign-in
# makes, and Apple.
SIGN_IN_HOSTS = re.compile(r"accounts\.google\.(?:com|(?:com?\.)?[a-z]{2})|accounts\.youtube\.com|appleid\.apple\.com")

PROFILE_DIRECTORY = "Default"
NEW_TAB_URLS = frozenset({"about:blank", "chrome://new-tab-page/", "chrome://new-tab-page", "chrome://newtab/", "chrome://newtab"})
# A dialog is accepted unless it is a prompt: a prompt wants input nobody has.
ACCEPTED_DIALOGS = frozenset({"alert", "confirm", "beforeunload"})
# The keys `Page.press` knows, as (code, windowsVirtualKeyCode).
KEY_CODES = {"Escape": ("Escape", 27)}

