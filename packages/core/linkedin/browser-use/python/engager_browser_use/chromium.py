"""Engager's Chromium, launched and driven over CDP with `cdp-use` alone.

The sidecar needs a handful of things from a browser: start the pinned Chromium
(or attach to one), list and open tabs, run a page function, navigate, press a
key, and hand the CDP client and a tab's session to the code that listens to its
network. This module is those things and nothing else -- no agent, no DOM
index, no event bus -- so the sidecar's Python environment is `cdp-use` and the
three packages it needs.

What a launch keeps from the library this replaced: the flags (`DEFAULT_ARGS`
is its list, less the one entry `ignore_default_args` dropped), the profile and
its directory, the off-screen window position, the redirect of a new-tab page
to `about:blank`, JavaScript dialogs answered so a page cannot hold a
navigation, and a tab that lands outside LinkedIn sent back to `about:blank`.
One thing it adds: while the owner is signing in, a tab may also be on the page
of a sign-in provider LinkedIn hands them to (`owner_signing_in`).
"""

